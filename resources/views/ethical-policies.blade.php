                        <h2>Ethical Policy & Client Agreement</h2>
                        <p>
                            This Ethical Policy and Client Agreement (“Agreement”) sets out the principles, standards, and conditions governing all business engagements between <strong>Nai Prints Corporation</strong> (hereinafter referred to as “Nai Prints”, “Service Provider”, or “the Company”) and its clients, including companies, organizations, and individuals (hereinafter referred to as “Client”). This document is intended to promote transparency, professionalism, accountability, and ethical conduct in all contractual relationships.
                        </p>

                        <h2>1. Purpose and Scope</h2>
                        <p>The purpose of this policy is to:</p>
                        <ul>
                            <li>Establish ethical standards for all contracts, tenders, and service engagements.</li>
                            <li>Protect both Nai Prints and the Client from unethical practices, misunderstandings, or contractual disputes.</li>
                            <li>Ensure fairness, integrity, and professionalism throughout the service delivery process.</li>
                        </ul>
                        <p>This policy applies to all printing, branding, design, production, installation, and related services offered by Nai Prints.</p>

                        <h2>2. Reliability and Contractual Integrity</h2>
                        <p>2.1 Nai Prints is committed to honoring all duly executed contracts and service agreements in good faith, in accordance with agreed specifications, timelines, and terms.</p>
                        <p>2.2 The Client similarly undertakes to act in good faith and acknowledges responsibility for compliance with all contractual obligations once an agreement is executed.</p>
                        <p>2.3 Any form of <strong>contract violation</strong>, whether by Nai Prints or the Client, shall be addressed through responsible, lawful, and professional means as outlined in this Agreement.</p>

                        <h2>3. Zero Tolerance to Kickbacks and Unethical Inducements</h2>
                        <p>3.1 Nai Prints maintains a strict zero-tolerance policy toward kickbacks, bribes, commissions, facilitation fees, or any form of unethical inducement related to contracts or tenders.</p>
                        <p>3.2 Nai Prints shall not enter into any contract or tender with a company or individual who:</p>
                        <ul>
                            <li>Requests or implies kickbacks or personal benefits.</li>
                            <li>Seeks unethical influence over procurement, pricing, or service allocation.</li>
                            <li>Encourages violation of procurement laws, tender procedures, or internal policies.</li>
                        </ul>
                        <p>3.3 Any Client found to be engaging in or proposing such practices may have their engagement terminated immediately, without liability to Nai Prints.</p>

                        <h2>4. Handling of Contract Breaches</h2>
                        <p>4.1 In the event of a breach of contract by either Nai Prints or the Client, the matter shall be handled responsibly, professionally, and in good faith.</p>
                        <p>4.2 The parties agree to:</p>
                        <ul>
                            <li>Notify each other in writing upon identification of a breach.</li>
                            <li>Allow reasonable opportunity for clarification, correction, or remedy where applicable.</li>
                            <li>Seek amicable resolution before pursuing legal remedies.</li>
                        </ul>
                        <p>4.3 Where resolution cannot be reached amicably, the matter may be escalated in accordance with applicable laws and dispute resolution mechanisms.</p>

                        <h2>5. Artwork, Document Approval & Client Responsibility</h2>
                        <p>5.1 The Client is required to carefully review and confirm all artworks, layouts, designs, specifications, and documents provided by Nai Prints prior to execution or printing.</p>
                        <p>5.2 The Client must:</p>
                        <ul>
                            <li>Provide written or digital confirmation of approval.</li>
                            <li>Sign and return the approved artwork and/or agreement.</li>
                        </ul>
                        <p>5.3 No printing, production, or execution shall commence until Nai Prints receives the signed approval from the Client.</p>
                        <p>5.4 Nai Prints shall not be held responsible for errors, omissions, or inaccuracies in artworks or documents that were approved and signed by the Client.</p>

                        <h2>6. Non-Coercion and Non-Influence Policy</h2>
                        <p>6.1 The Client or its representatives shall not coerce, pressure, influence, or induce any Nai Prints employee to:</p>
                        <ul>
                            <li>Deliver services outside agreed timelines.</li>
                            <li>Provide preferential treatment or favors.</li>
                            <li>Bypass standard procedures or quality controls.</li>
                        </ul>
                        <p>6.2 Any attempt to influence Nai Prints staff for quick delivery, personal favor, or deviation from agreed terms shall render the Client fully responsible for any resulting error, delay, or problem.</p>
                        <p>6.3 Nai Prints reserves the right to suspend or terminate services where such conduct is identified.</p>

                        <h2>7. Ethical Questioning and Contractual Clarification</h2>
                        <p>7.1 Nai Prints reserves the right to conduct ethical questioning and due diligence where contradictions, inconsistencies, or ambiguities arise in:</p>
                        <ul>
                            <li>Contract terms.</li>
                            <li>Artwork specifications.</li>
                            <li>Pricing, quantities, or delivery instructions.</li>
                        </ul>
                        <p>7.2 Such questioning shall be conducted professionally and solely for the purpose of:</p>
                        <ul>
                            <li>Protecting both parties’ interests.</li>
                            <li>Ensuring compliance with this Agreement.</li>
                            <li>Preventing disputes or unethical practices.</li>
                        </ul>
                        <p>7.3 The Client agrees to cooperate fully in providing clarification when reasonably requested.</p>

                        <h2>8. Confidentiality and Professional Conduct</h2>
                        <p>8.1 All client information, designs, and documents shall be handled with confidentiality and professionalism.</p>
                        <p>8.2 Both parties agree to maintain respectful communication and ethical conduct throughout the engagement.</p>

                        <h2>9. Governing Law</h2>
                        <p>This Agreement shall be governed and interpreted in accordance with the laws of the Republic of Kenya, unless otherwise agreed in writing.</p>

                        <h2>10. Acceptance and Binding Effect</h2>
                        <p>By signing below, both parties confirm that they:</p>
                        <ul>
                            <li>Have read and understood this Ethical Policy & Client Agreement.</li>
                            <li>Agree to be bound by its terms and conditions.</li>
                            <li>Commit to ethical, transparent, and professional engagement.</li>
                        </ul>

